// node scripts/gen-capability-rows.mjs: copy the capability sheet's axis rows (config/jfrog_capabilities.md)
// into src/lib/capabilityRows.ts, which the browser uses. npm test fails if the copy drifts from the sheet.
import { readFileSync, writeFileSync } from "node:fs";
import { parseSheet } from "../src/lib/capabilitySheet.ts";

const md = readFileSync(new URL("../../config/jfrog_capabilities.md", import.meta.url), "utf8");
const rows = parseSheet(md);
if (rows.length !== 7) throw new Error(`expected 7 axis rows, found ${rows.length}`);
const out = `// Generated by scripts/gen-capability-rows.mjs from config/jfrog_capabilities.md. Do not edit; rerun the script.
import type { SheetRow } from "./capabilitySheet";

export const CAPABILITY_ROWS: SheetRow[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL("../src/lib/capabilityRows.ts", import.meta.url), out);
console.log(`wrote ${rows.length} rows`);
